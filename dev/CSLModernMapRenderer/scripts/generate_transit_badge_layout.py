"""Regenerate the offline Viewer's copy of the PNG layout with requirements-dev installed."""
from hashlib import sha256
from pathlib import Path

from pscript import py2js

render = Path(__file__).resolve().parents[1]
source = (render / 'csmodernmap/transit_badge_layout.py').read_text(encoding='utf-8')
compiled = py2js(source, docstrings=False)
exports = ', '.join(sorted(name for name in compiled.meta['vars_defined'] if not name.startswith('_')))
output = (f'// Generated by generate_transit_badge_layout.py. Source SHA256: {sha256(source.encode()).hexdigest()}\n'
          '// PScript runtime helpers are distributed under ../PScript-LICENSE.txt.\n'
          f'{compiled}\nexport {{ {exports} }};\n')
(render / 'viewer/src/transit-badge-layout.js').write_text(output, encoding='utf-8', newline='\n')
